// LANGUAGE SETTINGS
// =========================================

const STORAGE_KEY = "avessada-language";
const DEFAULT_LANGUAGE = "en";

// =========================================
// GET SAVED LANGUAGE
// =========================================

function getStoredLanguage() {
    try {
        const stored = localStorage.getItem(STORAGE_KEY);

        return stored && translations[stored]
            ? stored
            : DEFAULT_LANGUAGE;
    } catch {
        return DEFAULT_LANGUAGE;
    }
}

// =========================================
// TRANSLATE PAGE
// =========================================

function translatePage(language) {
    const dictionary = translations[language] || translations.en;

    document.documentElement.lang = language;

    // Translate text content.
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        const translation = dictionary[key];

        if (typeof translation === "string") {
            element.textContent = translation;
        }
    });

    // Translate placeholders.
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        const translation = dictionary[key];

        if (typeof translation === "string") {
            element.placeholder = translation;
        }
    });

    // Translate accessible labels.
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        const key = element.dataset.i18nAriaLabel;
        const translation = dictionary[key];

        if (typeof translation === "string") {
            element.setAttribute("aria-label", translation);
        }
    });

    // Translate the document title.
    const titleKey = document.body.dataset.titleKey;

    if (titleKey && dictionary[titleKey]) {
        document.title = dictionary[titleKey];
    }

    // Translate the meta description.
    const descriptionKey = document.body.dataset.descriptionKey;
    const description = document.querySelector(
        'meta[name="description"]'
    );

    if (descriptionKey && description && dictionary[descriptionKey]) {
        description.content = dictionary[descriptionKey];
    }

    // Update the active language button.
    document.querySelectorAll("[data-lang]").forEach((button) => {
        const isActive = button.dataset.lang === language;

        button.classList.toggle("is-active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    // Save the selected language.
    try {
        localStorage.setItem(STORAGE_KEY, language);
    } catch {
        // Translation still works if localStorage is unavailable.
    }

    // Notify other scripts that the language has changed.
    document.dispatchEvent(
        new CustomEvent("languageChanged", {
            detail: { language }
        })
    );
}

// =========================================
// INITIALIZE LANGUAGE SELECTOR
// =========================================

document.addEventListener("DOMContentLoaded", () => {
    translatePage(getStoredLanguage());

    document.querySelectorAll("[data-lang]").forEach((button) => {
        button.addEventListener("click", () => {
            const language = button.dataset.lang;

            if (translations[language]) {
                translatePage(language);
            }
        });
    });
});

// =========================================
// UPDATE EXISTING FORM FEEDBACK
// =========================================

document.addEventListener("languageChanged", (event) => {
    const message = document.querySelector("[data-form-message]");

    if (!message || !message.dataset.messageKey) {
        return;
    }

    const language = event.detail.language;
    const key = message.dataset.messageKey;

    message.textContent =
        translations[language]?.[key] ||
        translations.en[key] ||
        "";
});

// =========================================
// DISPLAY FORM FEEDBACK
// =========================================

document.addEventListener("formMessageRequested", (event) => {
    const message = document.querySelector("[data-form-message]");

    if (!message) {
        return;
    }

    const { key, language, type } = event.detail;

    message.textContent =
        translations[language]?.[key] ||
        translations.en[key] ||
        "";

    message.dataset.messageKey = key;

    message.className = `form-message is-visible is-${type}`;
});